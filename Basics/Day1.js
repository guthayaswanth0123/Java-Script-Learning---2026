// Object-oriented programming is a programming approach in which we organize code around objects.
// An object contains:
// - Properties – Data or characteristics.
// - Methods – Functions or behaviours.

// 3. Multi-Paradigm Programming Language
// Paradigm means an approach or style of writing programs.
// Multi-paradigm means JavaScript supports multiple programming approaches instead of forcing developers to follow only one approach.
// JavaScript mainly supports these three styles:
//1. Procedural Programming -> Writing instructions step by step.
//2. Object-Oriented Programming -> Organizing code using objects and classes.
//3. Functional Programming -> Using functions to perform operations and process data.

